const collator = new Intl.Collator('en', { sensitivity: 'base' });

export const ISO_COUNTRIES: ReadonlyArray<IsoCountry> = Object.freeze(
  RAW_COUNTRIES.slice().sort((a, b) => collator.compare(a.name, b.name)),
);

const BY_CODE: ReadonlyMap<string, IsoCountry> = new Map(ISO_COUNTRIES.map((country) => [country.code, country]));

const REGIONAL_INDICATOR_OFFSET = 127397;

export function isoCountry(code: string | null | undefined): IsoCountry | null {
  if (typeof code !== 'string') return null;
  return BY_CODE.get(code.trim().toUpperCase()) ?? null;
}

export function flagOf(code: string | null | undefined): string {
  const clean = typeof code === 'string' ? code.trim().toUpperCase() : '';
  if (!/^[A-Z]{2}$/.test(clean)) return '';
  return String.fromCodePoint(...Array.from(clean, (letter) => REGIONAL_INDICATOR_OFFSET + letter.charCodeAt(0)));
}

export function currencyCodeOf(code: string | null | undefined): string | null {
  return isoCountry(code)?.currency ?? null;
}

export function countryOptions(exclude: Iterable<string> = []): CountryOption[] {
  const taken = new Set(Array.from(exclude, (code) => code.trim().toUpperCase()));
  return ISO_COUNTRIES.filter((country) => !taken.has(country.code)).map((country) => ({
    value: country.code,
    label: country.name,
    description: `${country.code} · ${country.currency} · ${country.symbol}`,
    keywords: [country.code, country.currency],
  }));
}
